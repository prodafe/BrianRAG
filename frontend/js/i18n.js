let LANG = (navigator.language || 'zh').startsWith('zh') ? 'zh' : 'en';

function t(key) {
  const dict = I18N[LANG] || I18N['zh'];
  return dict[key] || I18N['zh'][key] || key;
}

function setLang(lang) {
  LANG = lang;
  localStorage.setItem('brianrag_lang', lang);
}

// Restore saved language preference
(function() {
  const saved = localStorage.getItem('brianrag_lang');
  if (saved && (saved === 'zh' || saved === 'en')) LANG = saved;
})();
